// ---------- Расчёт пряжи ----------
// Эвристика для платочной вязки (проверена на типичных шарфах: полушерсть ~225 м / 100 г на спицах 4,5 мм
// даёт около 0,125 м нити на 1 см² полотна; шарф 18×152 см по готовым описаниям — 320–365 м).
// Для другой толщины: длина нити на см² растёт примерно как корень из метража (тоньше нить → больше петель
// и рядов, но каждая петля короче). Коэффициенты вязок: резинка 2×2 стягивается → ×1,3; гладь — ×0,85.
// Это оценка «с запасом», а не точная наука: точнее всего — взвесить свой постиранный образец.
const BASE_M_PER_CM2 = 0.125;      // м/см² для платочной вязки при 225 м / 100 г
const BASE_M_PER_100G = 225;
const STITCH_FACTOR = { garter: 1, rib: 1.3, stockinette: 0.85 };

/**
 * Сколько мотков нужно на прямоугольное изделие (шарф).
 * @param {object} o
 * @param {number} [o.lengthCm=160]      длина, см
 * @param {number} [o.widthCm=20]        ширина, см
 * @param {number} [o.metersPerSkein=225] метраж одного мотка, м
 * @param {number} [o.gramsPerSkein=100]  вес одного мотка, г
 * @param {'garter'|'rib'|'stockinette'} [o.stitch='garter'] вязка
 * @param {number} [o.margin=0.15]       запас (0,15 = +15 %)
 * @param {number} [o.swatchSkeins=1]    мотков сверху — на образцы и тренировки
 * @returns {null | { areaCm2, metersPerCm2, meters, metersWithMargin, grams, skeins, skeinsTotal }}
 *   meters — оценка без запаса; skeins — мотков на само изделие с запасом; skeinsTotal — плюс на образцы.
 *   null, если какие-то числа не заданы или не положительные.
 */
export function calcSkeins({
  lengthCm = 160, widthCm = 20, metersPerSkein = 225, gramsPerSkein = 100,
  stitch = 'garter', margin = 0.15, swatchSkeins = 1,
} = {}) {
  const nums = [lengthCm, widthCm, metersPerSkein, gramsPerSkein].map(Number);
  if (nums.some((n) => !Number.isFinite(n) || n <= 0)) return null;
  const [L, W, mps, gps] = nums;
  const metersPer100g = (mps / gps) * 100;
  const metersPerCm2 = BASE_M_PER_CM2 * Math.sqrt(metersPer100g / BASE_M_PER_100G) * (STITCH_FACTOR[stitch] ?? 1);
  const areaCm2 = L * W;
  const meters = areaCm2 * metersPerCm2;
  const metersWithMargin = meters * (1 + (Number(margin) || 0));
  const skeins = Math.ceil(metersWithMargin / mps);
  return {
    areaCm2,
    metersPerCm2: Math.round(metersPerCm2 * 1000) / 1000,
    meters: Math.round(meters),
    metersWithMargin: Math.round(metersWithMargin),
    grams: Math.round((metersWithMargin / mps) * gps),
    skeins,
    skeinsTotal: skeins + Math.max(0, Math.round(Number(swatchSkeins) || 0)),
  };
}

