// Ключи Firebase для синхронизации между телефоном и компьютером.
//
// Пока здесь null, трекер работает в режиме «только на этом устройстве»:
// всё хранится в браузере, сеть не нужна, Firebase даже не загружается.
//
// Как включить синхронизацию (бесплатный тариф Spark):
//  1. https://console.firebase.google.com → «Добавить проект» (Google Analytics не нужен).
//  2. Сборка → Authentication → «Начать» → Способы входа: включите «Google»
//     и «Электронная почта/пароль» + переключатель «Ссылка на эл. почту (вход без пароля)».
//  3. Authentication → Настройки → «Разрешённые домены»: добавьте домен сайта,
//     например  ваше-имя.github.io  (localhost там уже есть).
//  4. Сборка → Firestore Database → «Создать базу данных» (любой регион, рабочий режим),
//     затем вкладка «Правила» → вставьте содержимое файла firestore.rules → «Опубликовать».
//  5. Настройки проекта (шестерёнка) → «Ваши приложения» → значок </> (веб-приложение) →
//     зарегистрируйте приложение и скопируйте объект firebaseConfig сюда вместо null:
//
// export const firebaseConfig = {
//   apiKey: 'AIzaSy...',
//   authDomain: 'my-tracker.firebaseapp.com',
//   projectId: 'my-tracker',
//   storageBucket: 'my-tracker.appspot.com',
//   messagingSenderId: '1234567890',
//   appId: '1:1234567890:web:abc123def456',
// };
//
// Эти ключи не секретные: данные защищают правила Firestore (доступ только владельцу).

